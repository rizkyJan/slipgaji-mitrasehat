    public static function category(string $ptkp): string
    {
        return match ($ptkp) {
            'TK/2', 'TK/3', 'K/1', 'K/2' => 'B',
            'K/3' => 'C',
            default => 'A',
        };
    }

    public static function calculate(int $taxableGross, string $ptkp): array
    {
        $category = self::category($ptkp);
        foreach (self::TABLES[$category] as [$upper, $rate]) {
            if ($taxableGross <= $upper) {
                return [
                    'category' => $category,
                    'rate' => $rate,
                    'amount' => (int) round($taxableGross * $rate / 100, 0, PHP_ROUND_HALF_UP),
                ];
            }
        }
        throw new \LogicException('Tarif TER tidak ditemukan.');
    }
